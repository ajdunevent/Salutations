//! `X-Face:` headers: a 48×48 one-bit picture, compressed as one large
//! number written in printable characters. Decoding follows FFmpeg's
//! libavcodec/xface.c and xfacedec.c (LGPL-2.1-or-later, Stefano Sabatini),
//! which follow James Ashton's compface; the tables are theirs.

const W: usize = 48;
const PIXELS: usize = W * W;
/// The longest header compface writes; more is ignored.
const MAX_DIGITS: usize = 666;

/// The picture as a PNG, black on white; None when the header holds no
/// digits.
pub fn png(value: &str) -> Option<Vec<u8>> {
    let bits = decode(value)?;
    let mut rows = Vec::with_capacity(W * (W + 1));
    for row in bits.chunks(W) {
        rows.push(0); // no filter
        rows.extend(row.iter().map(|&b| if b { 0 } else { 255 }));
    }
    Some(gray_png(W as u32, W as u32, &rows))
}

/// One bit per pixel, row by row; true is black.
fn decode(value: &str) -> Option<Vec<bool>> {
    let mut big = Big(Vec::new());
    let mut digits = 0;
    for c in value.bytes().filter(|c| (b'!'..=b'~').contains(c)) {
        digits += 1;
        if digits > MAX_DIGITS {
            break;
        }
        big.mul(94);
        big.add(c - b'!');
    }
    if digits == 0 {
        return None;
    }
    let mut bits = vec![0u8; PIXELS];
    for (x, y) in [(0, 0), (16, 0), (32, 0), (0, 16), (16, 16), (32, 16), (0, 32), (16, 32), (32, 32)] {
        decode_block(&mut big, &mut bits, x + y * W, 16, 16, 0);
    }
    generate(&mut bits);
    Some(bits.into_iter().map(|b| b != 0).collect())
}

/// A non-negative number, least significant byte first.
struct Big(Vec<u8>);

impl Big {
    fn add(&mut self, a: u8) {
        let mut carry = a as u16;
        for w in self.0.iter_mut() {
            if carry == 0 {
                return;
            }
            carry += *w as u16;
            *w = carry as u8;
            carry >>= 8;
        }
        if carry != 0 {
            self.0.push(carry as u8);
        }
    }

    fn mul(&mut self, a: u16) {
        if a == 1 || self.0.is_empty() {
            return;
        }
        let mut carry = 0u32;
        for w in self.0.iter_mut() {
            carry += *w as u32 * a as u32;
            *w = carry as u8;
            carry >>= 8;
        }
        while carry != 0 {
            self.0.push(carry as u8);
            carry >>= 8;
        }
    }

    /// Takes off the lowest byte (a division by 256) and returns it.
    fn pop_byte(&mut self) -> u8 {
        if self.0.is_empty() { 0 } else { self.0.remove(0) }
    }

    /// Which of `ranges` the next value falls in.
    fn pop(&mut self, ranges: &[(u8, u8)]) -> usize {
        let r = self.pop_byte();
        // The ranges of each table cover 0 to 255, so one always matches.
        let i = ranges
            .iter()
            .position(|&(range, offset)| r >= offset && (r as u16) < range as u16 + offset as u16)
            .unwrap_or(0);
        let (range, offset) = ranges[i];
        self.mul(range as u16);
        self.add(r - offset);
        i
    }
}

const BLACK: usize = 0;
const WHITE: usize = 2;

/// (range, offset) by tree level: black, grey, white.
const LEVELS: [[(u8, u8); 3]; 4] = [
    [(1, 255), (251, 0), (4, 251)],
    [(1, 255), (200, 0), (55, 200)],
    [(33, 223), (159, 0), (64, 159)],
    [(131, 0), (0, 0), (125, 131)],
];

const GREYS: [(u8, u8); 16] = [
    (0, 0), (38, 0), (38, 38), (13, 152),
    (38, 76), (13, 165), (13, 178), (6, 230),
    (38, 114), (13, 191), (13, 204), (6, 236),
    (13, 217), (6, 242), (5, 248), (3, 253),
];

fn decode_block(big: &mut Big, bits: &mut [u8], at: usize, w: usize, h: usize, level: usize) {
    match big.pop(&LEVELS[level]) {
        WHITE => {}
        BLACK => pop_greys(big, bits, at, w, h),
        _ => {
            let (w, h) = (w / 2, h / 2);
            for off in [0, w, h * W, w + h * W] {
                decode_block(big, bits, at + off, w, h, level + 1);
            }
        }
    }
}

fn pop_greys(big: &mut Big, bits: &mut [u8], at: usize, w: usize, h: usize) {
    if w > 3 {
        let (w, h) = (w / 2, h / 2);
        for off in [0, w, W * h, W * h + w] {
            pop_greys(big, bits, at + off, w, h);
        }
        return;
    }
    let v = big.pop(&GREYS);
    for (bit, off) in [(1, 0), (2, 1), (4, W), (8, W + 1)] {
        if v & bit != 0 {
            bits[at + off] = 1;
        }
    }
}

/// Undoes compface's prediction: each pixel was stored as the difference
/// from a guess made from up to 12 pixels before it. The indexing,
/// including its edge cases, is compface's and must not change.
fn generate(bits: &mut [u8]) {
    let w = W as i32;
    for j in 0..w {
        for i in 0..w {
            let mut k: usize = 0;
            for l in i - 2..=i + 2 {
                for m in j - 2..=j {
                    if l <= 0 || (l >= i && m == j) {
                        continue;
                    }
                    if l <= w && m > 0 {
                        k = 2 * k + bits[(l + m * w) as usize] as usize;
                    }
                }
            }
            let table: &[u8] = match (i, j) {
                (1, 1) => G22,
                (1, 2) => G21,
                (1, _) => G20,
                (2, 1) => G12,
                (2, 2) => G11,
                (2, _) => G10,
                (47, 1) => G42,
                (47, 2) => G41,
                (47, _) => G40,
                (48, 1) => G32,
                (48, 2) => G31,
                (48, _) => G30,
                (_, 1) => G02,
                (_, 2) => G01,
                _ => G00,
            };
            let guess = table.get(k >> 3).map_or(0, |b| (b >> (7 - (k & 7))) & 1);
            bits[(i + j * w) as usize] ^= guess;
        }
    }
}

/// An 8-bit greyscale PNG of `rows` (each starting with its filter byte),
/// with uncompressed ("stored") deflate blocks.
fn gray_png(width: u32, height: u32, rows: &[u8]) -> Vec<u8> {
    let mut out = b"\x89PNG\r\n\x1a\n".to_vec();
    let mut ihdr = Vec::new();
    ihdr.extend(width.to_be_bytes());
    ihdr.extend(height.to_be_bytes());
    ihdr.extend([8, 0, 0, 0, 0]);
    chunk(&mut out, b"IHDR", &ihdr);
    let mut z = vec![0x78, 0x01];
    let blocks: Vec<&[u8]> = rows.chunks(65535).collect();
    for (n, block) in blocks.iter().enumerate() {
        z.push((n + 1 == blocks.len()) as u8);
        let len = block.len() as u16;
        z.extend(len.to_le_bytes());
        z.extend((!len).to_le_bytes());
        z.extend_from_slice(block);
    }
    z.extend(adler32(rows).to_be_bytes());
    chunk(&mut out, b"IDAT", &z);
    chunk(&mut out, b"IEND", &[]);
    out
}

fn chunk(out: &mut Vec<u8>, kind: &[u8; 4], data: &[u8]) {
    out.extend((data.len() as u32).to_be_bytes());
    let start = out.len();
    out.extend_from_slice(kind);
    out.extend_from_slice(data);
    let crc = crc32(&out[start..]);
    out.extend(crc.to_be_bytes());
}

fn crc32(data: &[u8]) -> u32 {
    let mut crc = !0u32;
    for &b in data {
        crc ^= b as u32;
        for _ in 0..8 {
            crc = if crc & 1 != 0 { (crc >> 1) ^ 0xedb8_8320 } else { crc >> 1 };
        }
    }
    !crc
}

fn adler32(data: &[u8]) -> u32 {
    let (mut a, mut b) = (1u32, 0u32);
    for &x in data {
        a = (a + x as u32) % 65521;
        b = (b + a) % 65521;
    }
    (b << 16) | a
}

