    #[test]
    fn decodes() {
        // Folded as in a header.
        let folded = format!("{}\n {}", &SAMPLE[..60], &SAMPLE[60..]);
        let bits = decode(&folded).unwrap();
        for (y, row) in ROWS.iter().enumerate() {
            for x in 0..W {
                assert_eq!(bits[y * W + x], row >> (W - 1 - x) & 1 == 1, "pixel {x},{y}");
            }
        }
    }

    #[test]
    fn png_shape() {
        let p = png(SAMPLE).unwrap();
        assert!(p.starts_with(b"\x89PNG\r\n\x1a\n"));
        assert!(png("   \n").is_none());
        assert_eq!(adler32(b"Wikipedia"), 0x11e6_0398);
        assert_eq!(crc32(b"123456789"), 0xcbf4_3926);
    }
